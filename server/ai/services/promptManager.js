function getSystemPrompt(pointAnalytics = null) {
    if (!pointAnalytics || typeof pointAnalytics !== 'object') {
        return SYSTEM_PROMPT;
    }
    const analyticsBlock = formatPointAnalyticsContext(pointAnalytics);
    return `${SYSTEM_PROMPT}\n\n${analyticsBlock}`;
}

